#!/usr/bin/env python3
"""Convert a progress workbook (format of HauXan2027_ProjectManagement.xlsx)
into SQL that loads one project into Project Hub.

Usage:
    python3 scripts/import_xlsx.py WORKBOOK.xlsx --code HCB2027 \
        --name "Houcan Cup 2027 (厚璨杯)" --lead TA > supabase/seed_project.sql

Expected sheets:
    1-Progress  header on row 4, data from row 6:
                ID, Phase, Task (EN), Task (ZH), Category, Owner code, Owner,
                Start, Deadline, Hours, Status, Self-reported %, ..., Date completed,
                ..., Deliverable / notes
    2-Members   header on row 4, data from row 5: Code, Name, Role, Responsibilities
    Lists       column H = phases, column I = categories

Run the output in the Supabase SQL editor AFTER schema.sql and after you
have made your own account admin. Your admin account becomes the lead member.
"""
import argparse
import datetime as dt
import json
import sys

import openpyxl

STATUS = {
    "not started": "not_started",
    "in progress": "in_progress",
    "done": "done",
    "on hold": "on_hold",
    "submitted": "submitted",
}


def q(v):
    """SQL literal."""
    if v is None or v == "":
        return "null"
    if isinstance(v, (dt.datetime, dt.date)):
        return "'%s'" % (v.date() if isinstance(v, dt.datetime) else v).isoformat()
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).strip().replace("'", "''") + "'"


def arr(items):
    return "array[" + ",".join(q(i) for i in items) + "]::text[]" if items else "'{}'::text[]"


def clean(v):
    if isinstance(v, str):
        v = v.strip()
        if v.startswith("="):  # formula cell, value not stored
            return None
        return v or None
    return v


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("workbook")
    ap.add_argument("--code", required=True)
    ap.add_argument("--name", required=True)
    ap.add_argument("--kind", default="led", choices=["led", "collab", "personal"])
    ap.add_argument("--lead", default="TA", help="member code that is you (the lead)")
    ap.add_argument("--visibility", default="all", choices=["all", "own"])
    ap.add_argument("--link", action="append", default=[], help="label=url, repeatable")
    a = ap.parse_args()

    wb = openpyxl.load_workbook(a.workbook, data_only=False)

    lists = wb["Lists"]
    phases = [clean(r[7]) for r in lists.iter_rows(min_row=2, values_only=True) if clean(r[7])]
    cats = [clean(r[8]) for r in lists.iter_rows(min_row=2, values_only=True) if clean(r[8])]

    members = []
    for r in wb["2-Members"].iter_rows(min_row=5, values_only=True):
        code = clean(r[0])
        if not code or len(code) > 8 or " " in code or "\n" in code:
            if members:
                break
            continue
        members.append(dict(code=code, name=clean(r[1]) or code, title=clean(r[2]), resp=clean(r[3])))

    tasks = []
    for r in wb["1-Progress"].iter_rows(min_row=6, values_only=True):
        if not clean(r[2]):
            continue
        status = STATUS.get(str(clean(r[10]) or "not started").lower(), "not_started")
        pct = clean(r[11])
        pct = int(round(float(pct) * 100)) if isinstance(pct, (int, float)) and pct <= 1 else (int(pct) if isinstance(pct, (int, float)) else 0)
        if status == "done":
            pct = 100
        tasks.append(dict(ref=clean(r[0]), phase=clean(r[1]), title=clean(r[2]), title_zh=clean(r[3]),
                          cat=clean(r[4]), owner=clean(r[5]), start=clean(r[7]), due=clean(r[8]),
                          hours=clean(r[9]) or 0, status=status, pct=pct, done=clean(r[13]),
                          deliv=clean(r[16])))

    links = []
    for item in a.link:
        label, _, url = item.partition("=")
        links.append({"label": label, "url": url})

    out = []
    w = out.append
    w("-- Generated by scripts/import_xlsx.py from %s" % a.workbook.split("/")[-1])
    w("-- %d members, %d tasks" % (len(members), len(tasks)))
    w("begin;")
    w("do $$")
    w("declare pid uuid; me uuid; m jsonb := '{}'::jsonb; mid uuid;")
    w("begin")
    w("  select id into me from public.profiles where is_admin order by created_at limit 1;")
    w("  if me is null then raise exception 'Make your account admin first (see README step 3).'; end if;")
    w("  insert into public.projects(code, name, kind, phases, categories, task_visibility, links)")
    w("  values (%s, %s, %s, %s, %s, %s, %s::jsonb) returning id into pid;"
      % (q(a.code), q(a.name), q(a.kind), arr(phases), arr(cats), q(a.visibility), q(json.dumps(links, ensure_ascii=False))))
    for mb in members:
        is_lead = mb["code"] == a.lead
        w("  insert into public.project_members(project_id, user_id, code, display_name, role, title, responsibilities)")
        w("  values (pid, %s, %s, %s, %s, %s, %s) returning id into mid;"
          % ("me" if is_lead else "null", q(mb["code"]), q(mb["name"]), q("lead" if is_lead else "member"),
             q(mb["title"]), q(mb["resp"])))
        w("  m := m || jsonb_build_object(%s, mid);" % q(mb["code"]))
    w("  insert into public.tasks(project_id, ref, phase, category, title, title_zh, assignee_id,")
    w("                           start_date, due_date, est_hours, status, progress, completed_at, deliverable) values")
    rows = []
    for t in tasks:
        assignee = "(m->>%s)::uuid" % q(t["owner"]) if t["owner"] else "null"
        rows.append("   (pid, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)" % (
            q(t["ref"]), q(t["phase"]), q(t["cat"]), q(t["title"]), q(t["title_zh"]), assignee,
            q(t["start"]), q(t["due"]), q(t["hours"]), q(t["status"]), q(t["pct"]), q(t["done"]), q(t["deliv"])))
    w(",\n".join(rows) + ";")
    w("end $$;")
    w("commit;")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
