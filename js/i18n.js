// Translate into a specific language (e.g. a message for someone else), not the viewer's.
export function tIn(l, key, vars) {
  let s = (STR[l] && STR[l][key]) ?? STR.en[key] ?? key;
  if (vars) for (const k in vars) s = s.replace('{' + k + '}', vars[k]);
  return s;
}
